const cache = {};
export function classInfo(cls) {
  if (cache[cls]) return cache[cls];
  const e = T[cls];
  const info = e
    ? { el: e[0], plural: e[1], cat: e[2], h: e[3], w: e[4], syn: e.slice(5), emoji: EMOJI[cls] || '🔹' }
    : { el: cls, plural: cls, cat: 'item', h: 0.4, w: 0.4, syn: [], emoji: '🔹' };
  cache[cls] = info;
  return info;
}
